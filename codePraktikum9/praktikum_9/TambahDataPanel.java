    private void kirimButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_kirimButtonActionPerformed
        // TODO add your handling code here:
        String nama = namaTextField.getText();
        String nim = nimTextField.getText();
        String prodi = (String) prodiComboBox.getSelectedItem();
        String jenisKelamin = lakilakiRadioButton.isSelected() ? "Laki-Laki" : "Perempuan" ; 
        boolean isActive = statusCheckBox.isSelected();
        if (nama.isEmpty() || nim.isEmpty() || (!lakilakiRadioButton.isSelected() && !perempuanRadioButton.isSelected()) || !isActive){
            JOptionPane.showMessageDialog(this, "Gagal menambahkan data!\nSilahkan lengkapi data terlebih dahulu");
            return;
        }
        try{
            long nimLong = Long.parseLong(nim);
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Gagal menambahkan data!\nNIM harus berupa angka");
            return;
        }
        
        if(mahasiswaToUpdate == null){
            Mahasiswa mahasiswaDuplikat = null;
            for(Mahasiswa mhs : Mahasiswa.mahasiswas){
                if(mhs.getNim().equals(nim)){
                    mahasiswaDuplikat = mhs;
                    break;
                }
            }
            if(mahasiswaDuplikat == null){
                Mahasiswa mahasiswa = new Mahasiswa(nama, nim, prodi, jenisKelamin, isActive);
                Mahasiswa.mahasiswas.add(mahasiswa);
                JOptionPane.showMessageDialog(this, "Berhasil menambahkan data mahasiswa " + nama);
                clearForm();
            }else {
                String pesan = "NIM " + nim + " sudah terdaftar untuk nama " + mahasiswaDuplikat.getNama();
                JOptionPane.showMessageDialog(this, pesan);
            }
        }else {
            if(!mahasiswaToUpdate.getNim().equals(nim)){
                for(Mahasiswa mhs : Mahasiswa.mahasiswas){
                    if(mhs.getNim().equals(nim) && mhs != mahasiswaToUpdate){
                        String pesan = "NIM " + nim + " sudah terdaftar untuk nama " + mhs.getNama();
                        JOptionPane.showMessageDialog(this, pesan);
                        return;
                    }
                }
            }
            mahasiswaToUpdate.setNama(nama);
            mahasiswaToUpdate.setNim(nim);
            mahasiswaToUpdate.setProdi(prodi);
            mahasiswaToUpdate.setJenisKelamin(jenisKelamin);
            mahasiswaToUpdate.setIsActive(isActive);
            JOptionPane.showMessageDialog(this, "Data berhasil di-update");
            mainFrame.changeMainPanel(new LihatDataPanel(mainFrame));
        }
    }//GEN-LAST:event_kirimButtonActionPerformed

