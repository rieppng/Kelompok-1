    public void updateForm(Mahasiswa mhs){
        namaTextField.setText(mhs.getNama());
        nimTextField.setText(mhs.getNim());
        prodiComboBox.setSelectedItem(mhs.getProdi());
        if(mhs.getJenisKelamin().equals("Laki-Laki")){
            lakilakiRadioButton.setSelected(true);
        }else{
            perempuanRadioButton.setSelected(true);
        }
        statusCheckBox.setSelected(mhs.isIsActive());
        this.mahasiswaToUpdate = mhs;
        titleLabel.setText("Update Data Mahasiswa");
        kirimButton.setText("Update"); 
    }
    
    
